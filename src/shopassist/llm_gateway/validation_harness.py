def load_recommendation_fixture(path: Path | None = None) -> RecommendationFixture:
    """Read one deterministic product/evidence sample without modifying frozen data."""
    import pandas as pd

    source = path or (Path(__file__).resolve().parents[3] / "data/processed/products.parquet")
    if not source.is_file():
        raise ValidationError("Frozen product catalog fixture is unavailable")
    try:
        frame = pd.read_parquet(source, columns=[
            "product_id", "product_name", "category", "retrieval_text",
        ])
        rows = frame.dropna(subset=["product_id", "product_name", "category", "retrieval_text"])
        row = next(
            record for record in rows.itertuples(index=False)
            if all(str(value).strip() for value in record)
        )
        product_id, product_name, category, retrieval_text = (str(value).strip() for value in row)
        evidence_text = retrieval_text[:1000].strip()
        if not evidence_text:
            raise ValueError
    except Exception:
        raise ValidationError("Frozen product catalog fixture could not be read safely") from None
    return RecommendationFixture(
        product_id=product_id, product_name=product_name, category=category,
        evidence_id=f"{product_id}-E1", evidence_text=evidence_text,
        catalog_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
    )


def _sample_request(route: ResolvedRoute, recommendation_fixture: RecommendationFixture | None = None) -> GatewayRequest:
    if route.route_id == "query_gemini":
        task, schema_id, schema = TaskType.QUERY_UNDERSTANDING, "phase8.query.v1", QueryUnderstandingOutput
        system = "Return only valid JSON matching the supplied query understanding schema."
        user = 'Extract the query intent: "comfortable black running shoes under INR 6000".'
    else:
        fixture = recommendation_fixture or load_recommendation_fixture()
        task, schema_id, schema = TaskType.RECOMMENDATION_GENERATION, "phase12.recommendation.v1", LLMRecommendationPayload
        system = (
            "Return only JSON matching the schema. Recommend exactly the supplied product. "
            "Use only the supplied evidence; cite its evidence ID for every factual claim."
        )
        user = (f'Query: "{fixture.product_name} {fixture.category}". Catalog candidate: '
                f"{fixture.product_id}, {fixture.product_name}, category {fixture.category}. "
                f'Catalog evidence [{fixture.evidence_id}]: "{fixture.evidence_text}". '
                f"Return exactly one explanation for product {fixture.product_id}.")
    return GatewayRequest(
        task=task, profile="default", request_id=uuid.uuid4().hex, task_id=uuid.uuid4().hex,
        system_prompt=system, user_prompt=user, schema_id=schema_id, response_schema=schema,
    )


def _estimate_tokens(request: GatewayRequest, route: ResolvedRoute) -> int:
    schema_bytes = json.dumps(request.response_schema.model_json_schema(), sort_keys=True).encode("utf-8")
    prompt_bytes = (request.system_prompt + request.user_prompt).encode("utf-8")
    # One token per UTF-8 byte plus schema and provider-side framing headroom.
    return len(prompt_bytes) + len(schema_bytes) + route.options["max_output_tokens"] + 512


def _validate_recommendation(payload: LLMRecommendationPayload,
                             fixture: RecommendationFixture) -> tuple[bool, bool]:
    expected_products = {fixture.product_id}
    expected_evidence = {fixture.evidence_id}
    ids_valid = len(payload.products) == 1 and {item.product_id for item in payload.products} == expected_products
    citations = [citation for product in payload.products
                 for claim in [*product.strengths, *product.limitations]
                 for citation in claim.evidence_ids]
    citations_valid = bool(citations) and all(value in expected_evidence for value in citations)
    return ids_valid, citations_valid


def _safe_usage(usage: GatewayUsage | None) -> GatewayUsage | None:
    if usage is None:
        return None
    return GatewayUsage(
        input_tokens=usage.input_tokens, output_tokens=usage.output_tokens,
        total_tokens=usage.total_tokens, reasoning_tokens=usage.reasoning_tokens,
        estimated_cost_usd=usage.estimated_cost_usd,
    )


def load_free_tier_evidence(path: Path, *, now: datetime | None = None) -> dict[tuple[str, str], FreeTierEvidence]:
    try:
        evidence_path = Path(path).resolve()
        raw = json.loads(evidence_path.read_text(encoding="utf-8"))
        evidence = [FreeTierEvidence.model_validate_json(json.dumps(item)) for item in raw]
    except Exception:
        raise ValidationError("Invalid or unavailable Free Tier entitlement evidence") from None
    now = now or datetime.now(timezone.utc)
    result = {}
    for item in evidence:
        if item.verified_at > now or item.expires_at <= now or (item.provider, item.model) in result:
            raise ValidationError("Free Tier entitlement evidence is expired, duplicated, or not yet valid")
        proof_path = (evidence_path.parent / item.artifact_ref).resolve()
        if (not proof_path.is_relative_to(evidence_path.parent) or not proof_path.is_file()
                or proof_path.stat().st_size > 2_000_000
                or entitlement_file_sha256(proof_path) != item.artifact_sha256):
            raise ValidationError("Free Tier entitlement artifact is missing or does not match its digest")
        result[(item.provider, item.model)] = item
    return result


def blocked_preflight_result(registry: ProviderRegistry, route_id: str, reason: str) -> ValidationResult:
    """Create a zero-attempt BLOCKED record for a failed local preflight."""
    if route_id not in _ROUTE_BINDINGS:
        raise ValidationError("Route is not an authorized T17 candidate")
    route = registry.resolve(route_id)
    _provider, _endpoint, model, task, schema_id, _mode, _schema = _ROUTE_BINDINGS[route_id]
    return ValidationResult(
        route_id=route_id, provider=route.provider, endpoint=route.endpoint,
        expected_model=model, task=task, schema_id=schema_id,
        status="blocked", attempt_count=0, safe_error=reason,
    )


class T17ValidationHarness:
    """One-call-per-candidate harness. No failover and no production approval."""

    def __init__(self, registry: ProviderRegistry, adapters: Mapping[str, ProviderAdapter],
                 budget: ValidationBudget, entitlements: Mapping[tuple[str, str], FreeTierEvidence],
                 credential_available: Callable[[ResolvedRoute], bool], *,
                 live_authorized: bool = False, paid_models_allowed: bool = False,
                 recommendation_fixture: RecommendationFixture | None = None):
        self.registry = registry
        self.adapters = adapters
        self.budget = budget
        self.entitlements = entitlements
        self.credential_available = credential_available
        self.live_authorized = live_authorized
        self.paid_models_allowed = paid_models_allowed
        self.recommendation_fixture = recommendation_fixture
        if paid_models_allowed:
            raise ValidationError("T17 is Free Tier only; paid models are disabled")

    def preflight(self, route_id: str) -> tuple[ResolvedRoute, FreeTierEvidence]:
        if route_id not in _ROUTE_BINDINGS:
            raise ValidationError("Route is not an authorized T17 candidate")
        route = self.registry.resolve(route_id)
        provider, endpoint, model, task_name, schema_id, structured_mode, schema = _ROUTE_BINDINGS[route_id]
        profile_task = TaskType(task_name)
        if (route.provider, route.endpoint, route.model, route.structured_mode) != (
            provider, endpoint, model, structured_mode
        ) or route.credential_env != _ROUTE_CREDENTIAL_ENVS[route_id] or schema_id not in route.schema_ids:
            raise ValidationError("T17 candidate route identity does not match the contract")
        if route.options["max_output_tokens"] != MAX_OUTPUT_TOKENS:
            raise ValidationError("T17 route output-token ceiling mismatch")
        if route.enabled or route.approval != "pending":
            raise ValidationError("T17 candidate must remain isolated with production route disabled/pending")
        if self.registry.profile_schema_id(profile_task, "default") != schema_id:
            raise ValidationError("T17 production profile schema mismatch")
        if route_id in {"recommendation_groq", "recommendation_gemini"} and self.recommendation_fixture is None:
            self.recommendation_fixture = load_recommendation_fixture()
        request = _sample_request(route, self.recommendation_fixture)
        if request.response_schema is not schema or route_id not in {
            item.route_id for item in self.registry.routes_for(request)
        }:
            raise ValidationError("T17 candidate is not bound to the exact task/schema profile")
        evidence = self.entitlements.get((route.provider, route.model))
        if evidence is None or evidence.tier != "free" or not evidence.paid_billing_disabled:
            raise ValidationError("Verified zero-paid-spend entitlement is required before dispatch")
        if not self.credential_available(route):
            raise ValidationError("Provider credential is unavailable")
        if not self.live_authorized:
            raise ValidationError("Explicit live authorization is required before dispatch")
        if self._adapter_for(route) is None:
            raise ValidationError("Provider adapter is unavailable")
        return route, evidence

    def _adapter_for(self, route: ResolvedRoute):
        return self.adapters.get(route.provider_profile) or self.adapters.get(route.provider)

    async def validate_one(self, route_id: str, *, attempt_timeout_s: float = ATTEMPT_TIMEOUT_SECONDS,
                           deadline_mono: float | None = None) -> ValidationResult:
        route, evidence = self.preflight(route_id)
        if attempt_timeout_s <= 0 or attempt_timeout_s > ATTEMPT_TIMEOUT_SECONDS:
            raise ValidationError("Attempt timeout exceeds the approved T17 limit")
        request = _sample_request(route, self.recommendation_fixture)
        estimate = _estimate_tokens(request, route)
        reservation = self.budget.reserve(route.provider, route.route_id, estimate)
        dispatched = False
        started = time.monotonic()

        def on_dispatch():
            nonlocal dispatched
            if dispatched:
                raise ValidationError("T17 adapter attempted a nested dispatch")
            if deadline_mono is not None and time.monotonic() >= deadline_mono:
                raise ValidationError("T17 run deadline exceeded before dispatch")
            self.budget.mark_dispatched(reservation)
            dispatched = True

        try:
            adapter = self._adapter_for(route)
            if adapter is None:
                raise ValidationError("Provider adapter is unavailable")
            prepared = adapter.prepare(request, route)
            remaining = attempt_timeout_s
            if deadline_mono is not None:
                remaining = min(remaining, deadline_mono - time.monotonic())
            if remaining <= 0:
                raise ValidationError("T17 run deadline exceeded before dispatch")
            result: AdapterResult = await asyncio.wait_for(
                adapter.complete_once(
                    prepared, timeout_s=remaining, on_dispatch=on_dispatch,
                ), timeout=remaining,
            )
            self.budget.settle(reservation, result.usage)
            payload = request.response_schema.model_validate_json(result.raw_text)
            if result.reported_model != route.model:
                raise ValidationError("Provider-reported model does not match the selected route")
            ids_valid = citations_valid = None
            fixture_hash = None
            review_payload = None
            if route_id in {"recommendation_groq", "recommendation_gemini"}:
                fixture = self.recommendation_fixture or load_recommendation_fixture()
                fixture_hash = fixture.catalog_sha256
                ids_valid, citations_valid = _validate_recommendation(payload, fixture)
                if not ids_valid or not citations_valid:
                    raise ValidationError("Recommendation product or evidence references do not match the test fixture")
                review_payload = {
                    "kind": "shopassist_phase18_t17_groundedness_review",
                    "created_at_utc": datetime.now(timezone.utc).isoformat(),
                    "route": {
                        "route_id": route.route_id, "provider": route.provider,
                        "endpoint": route.endpoint, "model": route.model,
                        "task": request.task.value, "schema_id": request.schema_id,
                    },
                    "catalog_fixture": fixture.model_dump(mode="json"),
                    "recommendation": payload.model_dump(mode="json"),
                }
            cost = result.usage.estimated_cost_usd
            if cost is not None and cost > MAX_TOTAL_COST_USD:
                raise ValidationError("Provider reported nonzero cost under zero-paid-spend policy")
            budget_state = self.budget.snapshot()
            if (budget_state["total_tokens"] > budget_state["max_total_tokens"]
                    or budget_state["tokens"][route.provider] > PROVIDER_BUDGETS[route.provider][1]):
                raise ValidationError("Provider-reported usage exceeded the T17 token ceiling; run stopped")
            return ValidationResult(
                route_id=route.route_id, provider=route.provider, endpoint=route.endpoint,
                expected_model=route.model, reported_model=result.reported_model,
                task=request.task.value, schema_id=request.schema_id, status="passed",
                output_schema_valid=True, recommendation_ids_valid=ids_valid,
                evidence_citations_valid=citations_valid,
                groundedness_review_required=(True if ids_valid is not None else None),
                catalog_fixture_sha256=fixture_hash, attempt_count=1,
                latency_ms=(time.monotonic() - started) * 1000, usage=_safe_usage(result.usage),
                actual_cost_usd=cost,
                entitlement_ref=hashlib.sha256(evidence.source_ref.encode("utf-8")).hexdigest(),
                review_payload=review_payload,
            )
        except asyncio.CancelledError:
            self.budget.settle(reservation, None)
            raise
        except Exception as exc:
            usage = exc.usage if isinstance(exc, ProviderAttemptError) else None
            self.budget.settle(reservation, usage)
            if isinstance(exc, ProviderAttemptError):
                category = exc.category.value
            elif isinstance(exc, ValidationError):
                category = str(exc)
            else:
                category = type(exc).__name__
            return ValidationResult(
                route_id=route.route_id, provider=route.provider, endpoint=route.endpoint,
                expected_model=route.model, task=request.task.value, schema_id=request.schema_id,
                status="failed" if dispatched else "blocked", attempt_count=1 if dispatched else 0,
                latency_ms=(time.monotonic() - started) * 1000,
                usage=_safe_usage(usage), safe_error=category,
                entitlement_ref=hashlib.sha256(evidence.source_ref.encode("utf-8")).hexdigest(),
            )


def build_live_adapters(providers: set[str] | None = None) -> dict[str, ProviderAdapter]:
    """Create lazy-credential adapters keyed by provider kind or profile alias."""
    selected = providers or {"gemini", "groq"}
    factories = {
        "gemini": lambda: GeminiAdapter(lambda: os.environ.get("GEMINI_API_KEY", "")),
        "gemini_recommendation": lambda: GeminiAdapter(lambda: os.environ.get("GEMINI_API_KEY_2", "")),
        "groq": lambda: GroqAdapter(lambda: os.environ.get("GROQ_API_KEY", "")),
    }
    return {provider: factories[provider]() for provider in selected}


def write_result_artifact(path: Path, results: list[ValidationResult], budget: ValidationBudget) -> None:
    """Write validation metadata and separate parsed recommendation review artifacts."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    for result in results:
        if result.review_payload is None:
            continue
        review_path = path.with_name(f"{path.stem}_{result.route_id}_groundedness_review.json")
        review_path.write_text(json.dumps(result.review_payload, indent=2, sort_keys=True), encoding="utf-8")
        result.groundedness_review_ref = review_path.name
    payload = {
        "kind": "shopassist_phase18_t17_validation",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "policy": {"paid_models_allowed": False, "max_cost_usd": str(MAX_TOTAL_COST_USD)},
        "budget": budget.snapshot(),
        "results": [item.model_dump(mode="json") for item in results],
    }
    path.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")


def entitlement_file_sha256(path: Path) -> str:
    """Fingerprint an operator evidence file without writing its contents to logs."""
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()
