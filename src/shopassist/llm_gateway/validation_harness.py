class ValidationBudget:
    """Crash-safe aggregate and per-provider request/token ceiling."""

    VERSION = 1

    def __init__(self, path: Path, *, max_total_requests: int = MAX_TOTAL_REQUESTS,
                 max_total_tokens: int = MAX_TOTAL_TOKENS,
                 max_cost_usd: Decimal = MAX_TOTAL_COST_USD):
        if not 1 <= max_total_requests <= MAX_TOTAL_REQUESTS:
            raise ValidationError("T17 total request ceiling exceeds the approved hard maximum")
        if not 1 <= max_total_tokens <= MAX_TOTAL_TOKENS:
            raise ValidationError("T17 total token ceiling exceeds the approved hard maximum")
        if Decimal(max_cost_usd) != MAX_TOTAL_COST_USD:
            raise ValidationError("T17 Free Tier policy requires a zero-cost ceiling")
        self.path = Path(path)
        self.max_total_requests = max_total_requests
        self.max_total_tokens = max_total_tokens
        self.max_cost_usd = Decimal(max_cost_usd)
        self._lock = threading.RLock()
        self.requests = {key: 0 for key in PROVIDER_BUDGETS}
        self.tokens = {key: 0 for key in PROVIDER_BUDGETS}
        self.reservations: dict[str, dict] = {}
        self._run_lock = None
        self._acquire_run_lock()
        try:
            self._load_existing()
        except Exception:
            self.close()
            raise

    def _acquire_run_lock(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        lock_path = self.path.with_suffix(self.path.suffix + ".lock")
        handle = lock_path.open("a+b")
        try:
            if os.name == "nt":
                import msvcrt
                handle.seek(0)
                if handle.read(1) == b"":
                    handle.seek(0)
                    handle.write(b"0")
                    handle.flush()
                handle.seek(0)
                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except (OSError, BlockingIOError):
            handle.close()
            raise ValidationError("T17 budget ledger is already in use") from None
        self._run_lock = handle

    def _load_existing(self):
        if self.path.exists():
            try:
                state = _BudgetLedger.model_validate_json(self.path.read_text(encoding="utf-8"))
                self.requests = state.requests
                self.tokens = state.tokens
                self.reservations = {key: item.model_dump() for key, item in state.reservations.items()}
                if set(self.requests) != set(PROVIDER_BUDGETS) or set(self.tokens) != set(PROVIDER_BUDGETS):
                    raise ValueError
                if any(value < 0 for value in (*self.requests.values(), *self.tokens.values())):
                    raise ValueError
                if any(self.requests[p] > PROVIDER_BUDGETS[p][0] or self.tokens[p] > PROVIDER_BUDGETS[p][1]
                       for p in PROVIDER_BUDGETS):
                    raise ValueError
                if sum(self.requests.values()) > self.max_total_requests or sum(self.tokens.values()) > self.max_total_tokens:
                    raise ValueError
                if any(item.route_id not in PROVIDER_ROUTE_IDS[item.provider]
                       for item in state.reservations.values()):
                    raise ValueError
            except Exception:
                raise ValidationError("Invalid validation budget ledger") from None
            # A dispatched but unsettled request is charged its reservation;
            # pre-dispatch reservations are safe to release after restart.
            for key, item in tuple(self.reservations.items()):
                if item["dispatched"]:
                    self.tokens[item["provider"]] += item["reserved_tokens"]
                del self.reservations[key]
            self._save()

    def close(self):
        handle = self._run_lock
        if handle is None:
            return
        try:
            if os.name == "nt":
                import msvcrt
                handle.seek(0)
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                import fcntl
                fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
        finally:
            handle.close()
            self._run_lock = None

    @property
    def total_requests(self) -> int:
        return sum(self.requests.values())

    @property
    def total_tokens(self) -> int:
        return sum(self.tokens.values())

    def _save(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        payload = {"version": self.VERSION, "requests": self.requests,
                   "tokens": self.tokens, "reservations": self.reservations}
        temp = self.path.with_suffix(self.path.suffix + ".tmp")
        temp.write_text(json.dumps(payload, sort_keys=True), encoding="utf-8")
        os.replace(temp, self.path)

    def reserve(self, provider: str, route_id: str, estimate: int) -> str:
        with self._lock:
            if provider not in PROVIDER_BUDGETS or estimate < 1:
                raise ValidationError("Invalid budget reservation")
            request_cap, token_cap = PROVIDER_BUDGETS[provider]
            held_requests = sum(1 for item in self.reservations.values()
                                if item["provider"] == provider and not item["dispatched"])
            held_tokens = sum(item["reserved_tokens"] for item in self.reservations.values())
            provider_held = sum(item["reserved_tokens"] for item in self.reservations.values()
                                if item["provider"] == provider)
            if self.total_requests + sum(not item["dispatched"] for item in self.reservations.values()) >= self.max_total_requests:
                raise ValidationError("T17 total request ceiling exhausted")
            if self.requests[provider] + held_requests >= request_cap:
                raise ValidationError("T17 provider request ceiling exhausted")
            if self.total_tokens + held_tokens + estimate > self.max_total_tokens:
                raise ValidationError("T17 total token ceiling would be exceeded")
            if self.tokens[provider] + provider_held + estimate > token_cap:
                raise ValidationError("T17 provider token ceiling would be exceeded")
            key = uuid.uuid4().hex
            self.reservations[key] = _Reservation(provider=provider, route_id=route_id,
                                                   reserved_tokens=estimate, dispatched=False).model_dump()
            self._save()
            return key

    def mark_dispatched(self, key: str):
        with self._lock:
            item = self.reservations.get(key)
            if not item or item["dispatched"]:
                raise ValidationError("Invalid T17 dispatch reservation")
            item["dispatched"] = True
            self.requests[item["provider"]] += 1
            self._save()

    def settle(self, key: str, usage: GatewayUsage | None):
        with self._lock:
            item = self.reservations.pop(key, None)
            if item is None:
                return
            if item["dispatched"]:
                actual = usage.total_tokens if usage else None
                if actual is None and usage and usage.input_tokens is not None and usage.output_tokens is not None:
                    actual = usage.input_tokens + usage.output_tokens
                self.tokens[item["provider"]] += item["reserved_tokens"] if actual is None else actual
            self._save()

    def snapshot(self) -> dict:
        with self._lock:
            return {"requests": dict(self.requests), "tokens": dict(self.tokens),
                    "total_requests": self.total_requests, "total_tokens": self.total_tokens,
                    "pending_reservations": len(self.reservations),
                    "max_total_requests": self.max_total_requests,
                    "max_total_tokens": self.max_total_tokens,
                    "max_cost_usd": str(self.max_cost_usd)}


