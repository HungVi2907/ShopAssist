class ValidationError(ValueError):
    """Safe, non-secret validation/preflight error."""


class FreeTierEvidence(BaseModel):
    """Operator-recorded account evidence; never generated by the harness."""

    model_config = ConfigDict(extra="forbid", strict=True)
    provider: Literal["gemini", "openrouter", "groq"]
    model: str = Field(min_length=1, max_length=128)
    account_ref_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    tier: Literal["free"]
    entitlement_verified: Literal[True]
    paid_billing_disabled: Literal[True]
    source_ref: str = Field(min_length=1, max_length=256)
    artifact_ref: str = Field(min_length=1, max_length=256)
    artifact_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    verified_at: datetime
    expires_at: datetime

    @field_validator("verified_at", "expires_at")
    @classmethod
    def require_utc(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None or value.utcoffset().total_seconds() != 0:
            raise ValueError("Entitlement timestamps must use UTC")
        return value

    @model_validator(mode="after")
    def valid_window(self):
        if self.expires_at <= self.verified_at:
            raise ValueError("Entitlement evidence expiry must follow verification")
        return self


