"""Data contracts and Pydantic schemas for Grounded Product Recommendation (Phase 12).

Defines structured schema models for:
- RecommendationStatus
- ProductEvidence and ProductClaim
- LLM-generation payload schemas (compatible with Groq JSON Schema Strict Mode)
- RecommendedProduct with authoritative metadata and grounded explanations
- TokenUsage and RecommendationResult (Phase 12 contract v1.0.0)
"""

from __future__ import annotations

from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class RecommendationStatus(str, Enum):
    """Execution status for the recommendation service."""

    SUCCESS = "SUCCESS"
    NO_RESULTS = "NO_RESULTS"
    INVALID_INPUT = "INVALID_INPUT"
    CLARIFICATION_REQUIRED = "CLARIFICATION_REQUIRED"
    UNSUPPORTED_INTENT = "UNSUPPORTED_INTENT"
    GENERATION_FAILURE = "GENERATION_FAILURE"
    VALIDATION_FAILURE = "VALIDATION_FAILURE"
    DETERMINISTIC_FALLBACK = "DETERMINISTIC_FALLBACK"


class ProductEvidence(BaseModel):
    """Verifiable piece of evidence extracted from catalog attributes."""

    model_config = ConfigDict(extra="ignore")

    evidence_id: str = Field(description="Unique identifier for the evidence item, e.g. 'P001-E1'.")
    product_id: str = Field(description="Stable product ID this evidence belongs to.")
    source_field: str = Field(description="Catalog field origin, e.g. 'product_name', 'specifications'.")
    text: str = Field(description="Exact snippet or factual value from the catalog.")


class ProductClaim(BaseModel):
    """Affirmative claim or limitation accompanied by supporting evidence references."""

    model_config = ConfigDict(extra="ignore")

    claim: str = Field(description="Factual claim describing product strength, limitation, or caveat.")
    evidence_ids: list[str] = Field(
        default_factory=list,
        description="List of verified evidence IDs supporting this claim. Empty for missing-attribute notes.",
    )


# ==============================================================================
# LLM Strict JSON Schema Models (for Groq generation in Strict Mode)
# ==============================================================================


class LLMProductClaim(BaseModel):
    """Claim representation for LLM structured output."""

    model_config = ConfigDict(extra="ignore")

    claim: str = Field(description="Concise factual claim regarding the product.")
    evidence_ids: list[str] = Field(
        description="Exact evidence IDs cited from the provided product evidence list. Must be empty if highlighting missing data.",
    )


class LLMProductExplanation(BaseModel):
    """Per-product explanation generated by the LLM."""

    model_config = ConfigDict(extra="ignore")

    product_id: str = Field(description="Exact product ID matching one of the provided candidate products.")
    summary_reason: str = Field(description="1-2 sentence explanation of why this product fits the user requirements.")
    strengths: list[LLMProductClaim] = Field(
        description="List of verified strengths supported by cited evidence IDs.",
    )
    limitations: list[LLMProductClaim] = Field(
        description="List of limitations, caveats, or missing attributes (empty evidence_ids for missing data).",
    )
    comparison_note: str | None = Field(
        default=None,
        description="Brief note on how this product compares with other candidate products in the set.",
    )


class LLMRecommendationPayload(BaseModel):
    """Top-level structured output expected from LLM generation."""

    model_config = ConfigDict(extra="ignore")

    overview: str = Field(
        description="Natural language summary introducing the recommendations in the user's language.",
    )
    products: list[LLMProductExplanation] = Field(
        description="List of product explanations corresponding exactly to the provided candidate products in order.",
    )


# ==============================================================================
# Final Assembled Recommendation Contracts
# ==============================================================================


class RecommendedProduct(BaseModel):
    """Final grounded recommendation item combining authoritative metadata and LLM explanations."""

    model_config = ConfigDict(extra="ignore")

    # Authoritative fields preserved from Phase 11
    product_id: str
    product_name: str
    brand: str | None = None
    category: str
    discounted_price: float
    rating: float | None = None
    currency: str = "INR"
    original_rank: int
    reranked_rank: int
    rrf_score: float

    # Grounded explanation fields
    summary_reason: str
    strengths: list[ProductClaim] = Field(default_factory=list)
    limitations: list[ProductClaim] = Field(default_factory=list)
    comparison_note: str | None = None

    # Traceable evidence catalog
    available_evidence: list[ProductEvidence] = Field(default_factory=list)


class TokenUsage(BaseModel):
    """Observability metadata for LLM token usage and latency."""

    model_config = ConfigDict(extra="ignore")

    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    reasoning_tokens: int = 0
    latency_ms: float = 0.0
    estimated_cost_usd: float = 0.0


class RecommendationResult(BaseModel):
    """Final typed recommendation result produced by Phase 12."""

    model_config = ConfigDict(extra="ignore")

    contract_version: str = "1.0.0"
    status: RecommendationStatus
    overview: str
    products: list[RecommendedProduct] = Field(default_factory=list)
    total_candidates_received: int = 0
    recommended_count: int = 0
    applied_constraints: dict[str, Any] = Field(default_factory=dict)
    language: str = "auto"
    model_name: str | None = None
    usage: TokenUsage = Field(default_factory=TokenUsage)
    warnings: list[str] = Field(default_factory=list)
    diagnostic_reason: str | None = None

    def to_dict(self) -> dict[str, Any]:
        """Convert result to dictionary representation."""
        return self.model_dump()

    def to_serializable_dict(self) -> dict[str, Any]:
        """Convert result to JSON-serializable dictionary representation."""
        return self.model_dump()
